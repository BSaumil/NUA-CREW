"""Generates docs/reports/HOSPITALITY_IMPORT_RECONCILIATION_2026-10-29.md from the committed seed.

    cd services/api && PYTHONPATH=. uv run python scripts/hospitality_report.py

Every number is computed from app/data/hospitality/*.json and the pay engine, never typed by hand.
"""

import collections
import re
import subprocess
from datetime import date, time
from decimal import Decimal
from pathlib import Path

from app.hospitality_schemas import PayAssessmentIn, RosterShiftIn
from app.services.hospitality.awards import assess
from app.services.hospitality.importer import load
from app.services.hospitality.rules import ruleset_from_seed

ROOT = Path(__file__).resolve().parents[3]
PDF = (
    ROOT
    / "docs/imports/hospitality/NUA_Crew_Hospitality_Roles_Hierarchy_Paygrades_Australia_2026-27.pdf"
)
OUT = ROOT / "docs/reports/HOSPITALITY_IMPORT_RECONCILIATION_2026-10-29.md"


def d(minor: int | None) -> str:
    return "n/a" if minor is None else f"${minor / 100:,.2f}"


def example(title, **over):
    base = dict(
        state="VIC",
        instrument="MA000119",
        coverage_confirmed=True,
        classification="L2",
        classification_confirmed=True,
        employment="casual",
        pay_period="hour",
        pay_amount=Decimal("33.85"),
    )
    base.update(over)
    inp = PayAssessmentIn(**base)
    rules = ruleset_from_seed(inp.instrument) if inp.instrument.startswith("MA") else None
    return title, inp, assess(inp, rules, effective_on=date(2026, 7, 15))


def main() -> None:
    roles_doc, awards = load("roles.json"), load("awards.json")
    roles = roles_doc["roles"]
    lines = ["# Hospitality import reconciliation — 29 October 2026", ""]
    lines += [
        "Generated by `services/api/scripts/hospitality_report.py` from the committed seed. "
        "Source workbook: `" + roles_doc["meta"]["source_workbook"] + "` "
        f"(sha256 `{roles_doc['meta']['source_sha256']}`).",
        "",
        "## Catalogue",
        "",
        f"- Roles imported: **{len(roles)}** (HC-0001 to HC-{len(roles):04d}, all stable IDs unique)",
        f"- Departments: **{len(roles_doc['departments'])}**",
        f"- Searchable aliases (variants + curated synonyms): **{sum(len(r['aliases']) for r in roles)}**",
        "",
        "| Department | Roles |",
        "| --- | ---: |",
    ]
    per = collections.Counter(r["department_code"] for r in roles)
    names = {x["code"]: x["name"] for x in roles_doc["departments"]}
    lines += [f"| {names[c]} | {n} |" for c, n in per.items()]
    titles = collections.defaultdict(list)
    for r in roles:
        titles[r["title"].strip().lower()].append(r)
    dups = {t: v for t, v in titles.items() if len(v) > 1}
    lines += ["", "## Duplicate titles (kept as separate roles; different departments)", ""]
    lines += [
        "| Title | Role IDs | Departments |",
        "| --- | --- | --- |",
    ]
    for v in dups.values():
        lines.append(
            f"| {v[0]['title']} | {', '.join(r['code'] for r in v)} | "
            f"{', '.join(names[r['department_code']] for r in v)} |"
        )
    lines += [
        "",
        f"{len(dups)} titles appear in more than one department. No role was merged or dropped: the "
        "brief asks to preserve all 287 source records unless a reconciliation shows a true "
        "duplicate, and a title shared by two departments is two different jobs on a roster. "
        "Search shows the department next to each so people can tell them apart.",
        "",
        "## Hierarchy tiers (1 = highest)",
        "",
        "| Tier | Roles |",
        "| ---: | ---: |",
    ]
    lines += [
        f"| {t} | {n} |" for t, n in sorted(collections.Counter(r["tier"] for r in roles).items())
    ]
    parsed = sum(1 for r in roles if r["indicative_level_min"] is not None)
    review = sum(1 for r in roles if r["needs_review"])
    lines += [
        "",
        "## Indicative classification text (a search aid, never a legal grade)",
        "",
        f"- Roles with a level range in the text (kept as `indicative_level_min/max`): **{parsed}**",
        f"- Roles flagged `needs_review` (management, trade, other award, apprentice, introductory or coverage wording): **{review}**",
        f"- Roles with no parseable level: **{len(roles) - parsed}**",
        "- No role is assigned an award classification by the import. The employer confirms the "
        "award and classification in every pay assessment.",
    ]
    lines += ["", "## Rate reconciliation", ""]
    rules = {
        c: ruleset_from_seed(c) for c in {r["instrument_code"] for r in awards["rate_versions"]}
    }
    matched = 0
    for rv in awards["rate_versions"]:
        rule = rules[rv["instrument_code"]].multiplier(
            "casual", rv["classification_code"], "weekday"
        )
        from app.services.hospitality.awards import apply_bp

        if (
            rule
            and apply_bp(rv["hourly_minor"], rule.multiplier_bp)
            == rv["supplied_casual_ordinary_minor"]
        ):
            matched += 1
    lines.append(
        f"- Workbook casual ordinary column vs hourly rate x 125% (half-up to the cent): "
        f"**{matched} of {len(awards['rate_versions'])}** rows agree."
    )
    try:
        text = subprocess.run(
            ["pdftotext", "-layout", str(PDF), "-"], capture_output=True, text=True, check=True
        ).stdout
        figures = set(re.findall(r"\$([\d,]+\.\d{2})", text))
        missing = []
        for rv in awards["rate_versions"]:
            for key in ("weekly_minor", "hourly_minor", "supplied_casual_ordinary_minor"):
                v = rv[key]
                if v and f"{v / 100:,.2f}" not in figures:
                    missing.append((rv["instrument_code"], rv["classification_code"], key, d(v)))
        lines.append(
            f"- PDF cross-check: every weekly, hourly and casual figure in the seed was searched in "
            f"the PDF text; **{sum(1 for _ in awards['rate_versions']) * 3 - len(missing)}** of "
            f"{len(awards['rate_versions']) * 3} appear as printed."
        )
        for m in missing:
            lines.append(f"  - not printed in the PDF section tables: {m[0]} {m[1]} {m[2]} {m[3]}")
        lines.append(
            "  (The PDF prints Restaurant/Hospitality Levels once for both awards; Fast Food and Clubs "
            "have their own tables. The Clubs operative levels 1–6 are stated to align numerically.)"
        )
    except (FileNotFoundError, subprocess.CalledProcessError):
        lines.append("- PDF cross-check skipped: `pdftotext` is not available here.")
    lines += [
        "- Hospitality (MA000009) and Restaurant (MA000119) base rates are identical in the supplied "
        "data for Introductory and Levels 1–6, as the PDF states; this is data as supplied, not a "
        "finding by NUA CREW.",
        "- **Every rate version and penalty rule is `supplied_unverified`.** An administrator marks a "
        "version `verified` (audited) after checking it against the official Fair Work pay guide. "
        "No figure here has been confirmed against Fair Work by this project.",
        "- Not loaded because the supplied data does not state them unambiguously: Registered Clubs "
        'weekend and public-holiday multipliers (the workbook says "common F&B grades; category can '
        'differ"), evening/night, overtime, allowances, junior/apprentice/trainee schedules, '
        "enterprise agreements, public holiday calendars.",
    ]
    lines += ["", "## Worked examples (computed by the engine)", ""]
    lines.append(
        "Adult, employer-confirmed coverage and classification, effective 15 July 2026, hourly pay "
        "excluding super. Minimums are what the award requires for that day; the offered column is "
        "the advertised casual rate."
    )
    lines += [
        "",
        "| Award | Level | Employment | Weekday | Saturday | Sunday | Public holiday |",
        "| --- | --- | --- | ---: | ---: | ---: | ---: |",
    ]
    cases = [
        ("MA000119", "L2", "casual"),
        ("MA000119", "L3", "casual"),
        ("MA000119", "L2", "part_time"),
        ("MA000009", "L2", "casual"),
        ("MA000009", "L2", "part_time"),
        ("MA000003", "FF1", "casual"),
        ("MA000003", "FF2", "casual"),
        ("MA000058", "L3", "casual"),
    ]
    for inst, lvl, emp in cases:
        _, _, r = example("", instrument=inst, classification=lvl, employment=emp)
        w = r.weekend_and_holiday_minimums
        lines.append(
            f"| {inst} | {lvl} | {emp} | {d(r.minimum_ordinary_hourly_minor)} | {d(w.get('saturday'))} | "
            f"{d(w.get('sunday'))} | {d(w.get('public_holiday'))} |"
        )
    lines += [
        "",
        "Clubs weekend and public-holiday cells show `n/a` on purpose: not loaded, not guessed.",
        "",
    ]
    lines += ["### Pay check scenarios", ""]
    scenarios = [
        example("Restaurant L2 casual at exactly the weekday minimum ($33.85)"),
        example("Restaurant L2 casual, one cent short ($33.84)", pay_amount=Decimal("33.84")),
        example(
            "Restaurant L2 casual flat $40.00 for all hours, Sunday roster",
            rate_structure="flat_all_hours",
            pay_amount=Decimal("40.00"),
            roster=[
                RosterShiftIn(
                    local_date=date(2026, 7, 19),
                    local_start=time(10),
                    local_end=time(16),
                    break_minutes=30,
                )
            ],
        ),
        example(
            "Hospitality L2 casual flat $44.00, same Sunday",
            instrument="MA000009",
            rate_structure="flat_all_hours",
            pay_amount=Decimal("44.00"),
            roster=[
                RosterShiftIn(
                    local_date=date(2026, 7, 19),
                    local_start=time(10),
                    local_end=time(16),
                    break_minutes=30,
                )
            ],
        ),
        example(
            "Coverage not confirmed, $20.00", coverage_confirmed=False, pay_amount=Decimal("20.00")
        ),
        example(
            "Enterprise agreement",
            instrument="enterprise_agreement",
            classification=None,
            classification_confirmed=False,
        ),
        example("Apprentice", worker_class="apprentice", pay_amount=Decimal("15.00")),
        example(
            "Annual salary $90,000 full-time",
            pay_period="year",
            pay_amount=Decimal("90000"),
            employment="full_time",
        ),
    ]
    lines += ["| Scenario | Status | Blocks publishing | Summary |", "| --- | --- | :---: | --- |"]
    for title, _, r in scenarios:
        lines.append(f"| {title} | `{r.status}` | {'yes' if r.blocking else 'no'} | {r.summary} |")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
